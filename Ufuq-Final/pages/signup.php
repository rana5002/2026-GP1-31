                }

                verification_clear(true); // also deletes the two files that were just uploaded
                $banner = 'We could not send the verification email. Please check the address and try again.';
            } catch (Throwable $ex) {
                error_log('Signup (company) failed: ' . $ex->getMessage());
                delete_files([$docPath, $logoPath]);
                $banner = 'Something went wrong. Please try again.';
            }
        }
    }
}

