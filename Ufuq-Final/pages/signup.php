// Banner text that names the fields to fix, e.g. "Please correct: Email, Phone."
function error_summary(array $errors, array $labels): string {
    $names = [];
    foreach (array_keys($errors) as $k) $names[] = $labels[$k] ?? $k;
    return 'Please correct: ' . implode(', ', array_unique($names)) . '.';
}
function arr_val(array $p, string $k, int $i): string {
    $a = $p[$k] ?? [];
    if (!is_array($a)) return '';
    $a = array_values($a);
    return (isset($a[$i]) && is_string($a[$i])) ? trim($a[$i]) : '';
}
function entry_count(array $p, string $k): int {
    return is_array($p[$k] ?? null) ? count($p[$k]) : 0;
}
/**
 * Experience entries: one chosen from the experience menu, plus job title, organization, start date and an
 * optional end date (empty = still ongoing). Duration is generated by the DB. Fully empty entries are ignored.
 * Each experience can be chosen only once.
 */
function parse_experience(array $p, array $menu, ?array &$bad, ?string &$err): array {
    $rows = []; $bad = []; $err = null; $seen = [];
    $today = new DateTime('today');
    for ($i = 0, $n = entry_count($p, 'exp_id'); $i < $n; $i++) {
        $id = arr_val($p, 'exp_id', $i);    $t  = arr_val($p, 'exp_title', $i);
        $o  = arr_val($p, 'exp_org', $i);   $s  = arr_val($p, 'exp_start', $i);
        $en = arr_val($p, 'exp_end', $i);
        if ($id === '' && $t === '' && $o === '' && $s === '' && $en === '') continue;
        $b = [];
        if (!ctype_digit($id) || !isset($menu[(int)$id]) || isset($seen[(int)$id])) $b[] = 'id'; else $seen[(int)$id] = true;
        if ($t === '' || mb_strlen($t) > MAX_JOB_TITLE) $b[] = 'title';
        if ($o === '' || mb_strlen($o) > MAX_ORG) $b[] = 'org';
        $sd  = DateTime::createFromFormat('!Y-m-d', $s);
        $sOk = $sd && $sd->format('Y-m-d') === $s && $sd <= $today;
        if (!$sOk) $b[] = 'start';
        $endVal = null;
        if ($en !== '') {
            $ed  = DateTime::createFromFormat('!Y-m-d', $en);
            $eOk = $ed && $ed->format('Y-m-d') === $en && $ed <= $today && (!$sOk || $ed >= $sd);
            if (!$eOk) $b[] = 'end'; else $endVal = $en;
        }
        if ($b) { $bad[$i] = $b; $err = EXP_ERR; } else { $rows[] = [(int)$id, $t, $o, $s, $endVal]; }
    }
    return $rows;
}
/**
 * Qualification entries: one chosen from the qualification menu, plus institution, year obtained and an
 * optional duration (years). Each qualification can be chosen only once.
 */
function parse_qualifications(array $p, array $menu, ?array &$bad, ?string &$err): array {
    $rows = []; $bad = []; $err = null; $seen = [];
    $yMax = (int)date('Y'); $yMin = $yMax - 60;
    for ($i = 0, $n = entry_count($p, 'qual_id'); $i < $n; $i++) {
        $id = arr_val($p, 'qual_id', $i);   $in = arr_val($p, 'qual_inst', $i);
        $yr = arr_val($p, 'qual_year', $i); $du = arr_val($p, 'qual_duration', $i);
        if ($id === '' && $in === '' && $yr === '' && $du === '') continue;
        $b = [];
        if (!ctype_digit($id) || !isset($menu[(int)$id]) || isset($seen[(int)$id])) $b[] = 'id'; else $seen[(int)$id] = true;
        if ($in === '' || mb_strlen($in) > MAX_INSTITUTION) $b[] = 'inst';
        if (!ctype_digit($yr) || (int)$yr < $yMin || (int)$yr > $yMax) $b[] = 'year';
        if ($du !== '' && (!ctype_digit($du) || (int)$du < 1 || (int)$du > 10)) $b[] = 'duration';
        if ($b) { $bad[$i] = $b; $err = QUAL_ERR; } else { $rows[] = [(int)$id, $in, (int)$yr, $du === '' ? null : (int)$du]; }
    }
    return $rows;
}
