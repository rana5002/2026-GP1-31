  /* ---------- Date of birth calendar (min age 15) ---------- */
  (function () {
    const dob = document.getElementById("uDob");
    if (!dob) return;
    const minD = dob.dataset.min, maxD = dob.dataset.max;
    if (typeof flatpickr === "undefined") {          // fallback: browser's native calendar
