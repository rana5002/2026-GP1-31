        if ($web !== '' && (!filter_var($web, FILTER_VALIDATE_URL) || mb_strlen($web) > MAX_URL)) $errors['website'] = 'Please enter a valid URL (https://...).';

        if ($emptyFound) {
            $banner = 'All required fields must be filled.';
        } elseif ($errors) {
            $banner = error_summary($errors, $LABELS_COMP);
        }

        // email or CR already registered?
        if (!$errors) {
            $st = $pdo->prepare('SELECT 1 FROM member WHERE Email = ?');
            $st->execute([$email]);
            $dupEmail = (bool)$st->fetchColumn();
            $st = $pdo->prepare('SELECT 1 FROM company WHERE CrNumber = ?');
            $st->execute([$cr]);
            $dupCr = (bool)$st->fetchColumn();
            if ($dupEmail || $dupCr) {
                $errors[$dupEmail ? 'email' : 'cr_number'] = 'Company already registered';
                $banner = 'Company already registered';
            }
        }

        // verify: keep everything in the session and email a 6-digit code (nothing is saved in the database yet)
        if (!$errors) {
            $docPath = ''; $logoPath = '';
            try {
                $docPath  = store_file('doc', 'docs');
                $logoPath = store_file('logo', 'logos');

                $code = verification_start([
                    'type' => 'Company', 'email' => $email, 'pass_hash' => password_hash($pass, PASSWORD_DEFAULT),
                    'name' => $name, 'cr' => $cr, 'phone' => $phone, 'industry' => $ind, 'loc' => $loc,
                    'desc' => $desc, 'web' => $web, 'doc' => $docPath, 'logo' => $logoPath,
                ]);

                $mail = email_verification_code($name, $code);
                if (send_mail($email, $mail['subject'], $mail['html'], $mail['text'])) {
                    header('Location: verify-code.php');
