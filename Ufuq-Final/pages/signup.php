        }

        if (!isset($errors['first_name']) && mb_strlen($first) > MAX_NAME) $errors['first_name'] = 'Maximum ' . MAX_NAME . ' characters.';
        if (!isset($errors['last_name'])  && mb_strlen($last)  > MAX_NAME) $errors['last_name']  = 'Maximum ' . MAX_NAME . ' characters.';
