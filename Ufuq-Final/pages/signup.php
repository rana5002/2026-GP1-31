        if (!isset($errors['phone']) && !preg_match(PHONE_USER, $phone)) $errors['phone'] = 'Phone number must start with 05 and be 10 digits (e.g. 05XXXXXXXX).';
        if (!isset($errors['edu_status']) && !in_array($edu, $EDU_STATUSES, true)) $errors['edu_status'] = 'Please select a valid option.';
        if (!isset($errors['field_of_study']) && mb_strlen($field) > MAX_FIELD) $errors['field_of_study'] = 'Maximum ' . MAX_FIELD . ' characters.';
        if (!isset($errors['gender']) && !in_array($gender, ['Male', 'Female'], true)) $errors['gender'] = 'Please select a gender.';

        if (!isset($errors['dob'])) {
            $dChk = DateTime::createFromFormat('!Y-m-d', $dob);
            if (!$dChk || $dChk->format('Y-m-d') !== $dob) {
                $errors['dob'] = 'Please enter a valid date of birth.';
            } else {
                $d   = new DateTime($dob);
                $age = (new DateTime('today'))->diff($d)->y;
                if ($d > new DateTime('today') || $age < 15) $errors['dob'] = 'You must be at least 15 years old.';
                elseif ($age > 100) $errors['dob'] = 'Please enter a valid date of birth.';
            }
        }

        if (!isset($errors['password']) && !is_strong_password($pass)) $errors['password'] = PW_MSG;
        if (!isset($errors['password2']) && $pass !== $pass2) $errors['password2'] = 'Passwords do not match.';

        $picState = check_file('picture', IMG_EXT, IMG_MIME);
        if ($picState === 'bad') $errors['picture'] = 'Invalid image format. Only PNG, JPG or JPEG are allowed.';

        $expRows  = parse_experience($p, $allExperiences, $expBad, $errExp);
        if ($errExp) $errors['experience'] = $errExp;
        $qualRows = parse_qualifications($p, $allQualifications, $qualBad, $errQual);
        if ($errQual) $errors['qualifications'] = $errQual;

        if ($emptyFound) {
            $banner = 'All fields are mandatory. Please check the highlighted fields.';
        } elseif ($errors) {
            $banner = error_summary($errors, $LABELS_USER);
        }

        // email already registered?
        if (!$errors) {
            $st = $pdo->prepare('SELECT 1 FROM member WHERE Email = ?');
            $st->execute([$email]);
            if ($st->fetchColumn()) {
                $errors['email'] = 'Email already registered';
                $banner = 'Email already registered';
            }
        }

        // verify: keep everything in the session and email a 6-digit code (nothing is saved in the database yet)
        if (!$errors) {
            $picPath = '';
            try {
                if ($picState === 'ok') { $picPath = store_file('picture', 'user-profile'); }

                // optional: skills chosen from the menu (only ids that exist in the skill table)
                $skillIds = [];
                foreach ((array)($p['skills'] ?? []) as $sid) {
                    if (is_string($sid) && ctype_digit($sid) && isset($allSkills[(int)$sid])) $skillIds[] = (int)$sid;
                }

                $code = verification_start([
                    'type' => 'User', 'email' => $email, 'pass_hash' => password_hash($pass, PASSWORD_DEFAULT),
                    'first' => $first, 'last' => $last, 'phone' => $phone, 'dob' => $dob,
                    'gender' => ($gender === 'Female') ? 'F' : 'M',   // the database stores one letter
                    'pic' => $picPath, 'edu' => $edu, 'field' => $field,
                    'exp' => $expRows, 'qual' => $qualRows, 'skills' => array_values(array_unique($skillIds)),
                ]);

                $mail = email_verification_code($first, $code);
                if (send_mail($email, $mail['subject'], $mail['html'], $mail['text'])) {
                    header('Location: verify-code.php');
                    exit;
                }

                verification_clear(true); // also deletes the picture that was just uploaded
                $banner = 'We could not send the verification email. Please check the address and try again.';
            } catch (Throwable $ex) {
                error_log('Signup (user) failed: ' . $ex->getMessage());
                delete_files([$picPath]);
                $banner = 'Something went wrong. Please try again.';
            }
        }
    }

    /* ---------- COMPANY ---------- */
    else {
        $name  = trim($p['company_name'] ?? '');
        $email = trim($p['email'] ?? '');
        $phone = trim($p['phone'] ?? '');
        $cr    = trim($p['cr_number'] ?? '');
        $ind   = $p['industry'] ?? '';
