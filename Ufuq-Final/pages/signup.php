$errors  = [];
$banner  = '';
$expBad = []; $qualBad = []; $expRows = []; $qualRows = [];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    csrf_check();

    $emptyFound = false;
    $p = $_POST;

    /* ---------- USER ---------- */
    if ($type === 'User') {
        $first  = trim($p['first_name'] ?? '');
        $last   = trim($p['last_name'] ?? '');
        $email  = trim($p['email'] ?? '');
        $phone  = trim($p['phone'] ?? '');
        $edu    = $p['edu_status'] ?? '';
        $field  = $p['field_of_study'] ?? '';
        if ($field === 'Other') $field = trim($p['field_other'] ?? '');
