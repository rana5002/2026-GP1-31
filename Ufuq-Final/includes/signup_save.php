<?php
// Saves a VERIFIED registration into the database. Called only after the email code is confirmed.
// Text values inside SQL use SINGLE quotes: on some servers (e.g. Aiven) double quotes mean a column name.

// Returns the new MemberID. Throws on failure (PDOException, errorInfo[1] === 1062 means "already registered").
function signup_save(PDO $pdo, array $d): int
{
    $pdo->beginTransaction();

    try {
        if (($d['type'] ?? '') === 'User') {
            $pdo->prepare("INSERT INTO member (Email, Password, Role) VALUES (?, ?, 'User')")
                ->execute([$d['email'], $d['pass_hash']]);
            $uid = (int) $pdo->lastInsertId();

            // Age is worked out here from the date of birth (the table has no trigger for it).
            $age = (new DateTime('today'))->diff(new DateTime($d['dob']))->y;

            $pdo->prepare('INSERT INTO `user` (UserID, FirstName, LastName, Phone, DateOfBirth, Age, Gender, ProfilePicture, EducationalStatus)
                           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)')
                ->execute([$uid, $d['first'], $d['last'], $d['phone'], $d['dob'], $age, $d['gender'],
                           ($d['pic'] ?? '') !== '' ? $d['pic'] : null, $d['edu']]);

            // Field of study: degree level, university and graduation year can be added later from the profile.
            $pdo->prepare('INSERT INTO userstudy (UserID, FieldOfStudy) VALUES (?, ?)')
                ->execute([$uid, $d['field']]);

            // Optional: experience (chosen from the experience menu, plus the user's own details). Duration is generated by the DB.
            foreach (($d['exp'] ?? []) as [$expId, $title, $org, $start, $end]) {
                $pdo->prepare('INSERT INTO userexperience (UserID, ExperienceID, JobTitle, Organization, StartDate, EndDate)
                               VALUES (?, ?, ?, ?, ?, ?)')
                    ->execute([$uid, $expId, $title, $org, $start, $end]);
            }

            // Optional: qualifications (chosen from the qualification menu, plus the user's own details)
            foreach (($d['qual'] ?? []) as [$qualId, $institution, $year, $duration]) {
                $pdo->prepare('INSERT INTO userqualification (UserID, QualificationID, Institution, YearObtained, Duration)
                               VALUES (?, ?, ?, ?, ?)')
                    ->execute([$uid, $qualId, $institution, $year, $duration]);
            }

            // Optional: skills (chosen from the skill menu)
            foreach (array_unique($d['skills'] ?? []) as $skillId) {
                $pdo->prepare('INSERT INTO userskill (UserID, SkillID) VALUES (?, ?)')
                    ->execute([$uid, (int) $skillId]);
            }

            $id = $uid;
        } else {
            $pdo->prepare("INSERT INTO member (Email, Password, Role) VALUES (?, ?, 'Company')")
                ->execute([$d['email'], $d['pass_hash']]);
            $cid = (int) $pdo->lastInsertId();

            $pdo->prepare("INSERT INTO company (CompanyID, CompanyName, CrNumber, Phone, IndustrySector, VerificationDocument, Status, Description, Location, WebsiteURL, Logo)
                           VALUES (?, ?, ?, ?, ?, ?, 'Pending', ?, ?, ?, ?)")
                ->execute([$cid, $d['name'], $d['cr'], $d['phone'], $d['industry'], $d['doc'],
                           $d['desc'], $d['loc'], ($d['web'] ?? '') !== '' ? $d['web'] : null, $d['logo']]);

            $id = $cid;
        }

        $pdo->commit();
        return $id;
    } catch (Throwable $ex) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        throw $ex;
    }
}