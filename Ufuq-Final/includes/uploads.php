<?php
declare(strict_types=1);

// Shared upload configuration.
const UPLOAD_FOLDERS = [
    'user-profile' => 'profile-pictures',
    'logos'        => 'logos',
    'docs'         => 'docs',
];

/**
 * Check uploaded file type and size.
 * Returns: 'none' | 'bad' | 'ok'
 */
function check_file(string $key, array $exts, array $mimes): string
{
    if (
        !isset($_FILES[$key]) ||
        $_FILES[$key]['error'] === UPLOAD_ERR_NO_FILE
    ) {
        return 'none';
    }

    $file = $_FILES[$key];

    if (
        $file['error'] !== UPLOAD_ERR_OK ||
        $file['size'] <= 0 ||
        $file['size'] > 5 * 1024 * 1024
    ) {
        return 'bad';
    }

    $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));

    if (!in_array($ext, $exts, true)) {
        return 'bad';
    }

    $mime = (new finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']);

    return in_array($mime, $mimes, true) ? 'ok' : 'bad';
}

/**
 * Store an uploaded file.
 * The database path format remains compatible with existing records.
 */
function store_file(string $key, string $sub): string
{
    if (
        !isset($_FILES[$key]) ||
        $_FILES[$key]['error'] !== UPLOAD_ERR_OK
    ) {
        throw new RuntimeException('File upload failed.');
    }

    $file = $_FILES[$key];
    $maxSize = 5 * 1024 * 1024;

    if ($file['size'] <= 0 || $file['size'] > $maxSize) {
        throw new RuntimeException(
            'File exceeds the 5 MB limit or is empty.'
        );
    }

    $allowed = [
        'user-profile' => ['png', 'jpg', 'jpeg'],
        'docs'         => ['pdf', 'png', 'jpg', 'jpeg'],
        'logos'        => ['png', 'jpg', 'jpeg'],
    ];

    $allowedMimes = [
        'png'  => 'image/png',
        'jpg'  => 'image/jpeg',
        'jpeg' => 'image/jpeg',
        'pdf'  => 'application/pdf',
    ];

    if (!isset(UPLOAD_FOLDERS[$sub], $allowed[$sub])) {
        throw new RuntimeException('Invalid upload category.');
    }

    $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));

    if (!in_array($ext, $allowed[$sub], true)) {
        throw new RuntimeException('Invalid file extension.');
    }

    $mime = (new finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']);

    if (($allowedMimes[$ext] ?? '') !== $mime) {
        throw new RuntimeException(
            'File content does not match its extension.'
        );
    }

    $folder = UPLOAD_FOLDERS[$sub];

    if ($sub === 'docs') {
       if ($sub === 'docs') {
    // Verification documents: Ufuq-Final/uploads/docs (direct access is blocked by .htaccess)
    $dir = __DIR__ . '/../uploads/docs';

    if (!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
        throw new RuntimeException('Could not create upload directory.');
    }

    $docsHtaccess = $dir . '/.htaccess';

    if (!is_file($docsHtaccess)) {
        file_put_contents(
            $docsHtaccess,
            "Options -Indexes\n\n# Block direct access to uploaded verification documents.\nRequire all denied\n",
            LOCK_EX
        );
    }
    } else {
        $uploadRoot = __DIR__ . '/../uploads';
        $dir = $uploadRoot . '/' . $folder;

        // Prevent directory listing and script execution in public uploads.
        if (!is_dir($uploadRoot)) {
            if (!mkdir($uploadRoot, 0755, true) && !is_dir($uploadRoot)) {
                throw new RuntimeException(
                    'Could not create upload directory.'
                );
            }
        }

        $rootHtaccess = $uploadRoot . '/.htaccess';

        if (!is_file($rootHtaccess)) {
            $rules = <<<'HTACCESS'
Options -Indexes
<FilesMatch "\.(php[0-9]?|phtml|phar|cgi|pl|py|sh)$">
    Require all denied
</FilesMatch>
HTACCESS;

            if (
                file_put_contents(
                    $rootHtaccess,
                    $rules . "\n",
                    LOCK_EX
                ) === false
            ) {
                throw new RuntimeException(
                    'Could not secure upload directory.'
                );
            }
        }
    }

    if (!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
        throw new RuntimeException('Could not create upload directory.');
    }

    $name = bin2hex(random_bytes(16)) . '.' . $ext;
    $destination = $dir . DIRECTORY_SEPARATOR . $name;

    if (!move_uploaded_file($file['tmp_name'], $destination)) {
        throw new RuntimeException('Could not save uploaded file.');
    }

    // Keep the existing database path format.
    return 'uploads/' . $folder . '/' . $name;
}

/**
 * Only accept paths generated by store_file().
 */
function upload_path_ok(string $path): bool
{
    return (bool) preg_match(
        '#^uploads/(profile-pictures|logos|docs)/[a-f0-9]{32}\.(png|jpg|jpeg|pdf)$#',
        $path
    );
}

/**
 * Resolve the actual filesystem path for an uploaded file.
 */
function stored_file_path(string $path): ?string
{
    if (!upload_path_ok($path)) {
        return null;
    }

   
    

    return __DIR__ . '/../' . $path;
}

/**
 * Delete uploaded files created by store_file().
 */
function delete_files(array $paths): void
{
    foreach ($paths as $path) {
        $fullPath = stored_file_path((string) $path);

        if ($fullPath !== null && is_file($fullPath)) {
            @unlink($fullPath);
        }
    }
}

/**
 * Mark uploaded files as recently used.
 */
function touch_files(array $paths): void
{
    foreach ($paths as $path) {
        $fullPath = stored_file_path((string) $path);

        if ($fullPath !== null && is_file($fullPath)) {
            @touch($fullPath);
        }
    }
}

/**
 * Remove old uploads that are not referenced by database records.
 */
function cleanup_orphan_uploads(
    PDO $pdo,
    int $maxAgeSeconds = 7200
): int {
    $used = [];

    $queries = [
        'SELECT ProfilePicture FROM `user`',
        'SELECT Logo FROM company',
        'SELECT VerificationDocument FROM company',
    ];

    foreach ($queries as $sql) {
        foreach ($pdo->query($sql)->fetchAll(PDO::FETCH_COLUMN) as $value) {
            if ($value !== null && $value !== '') {
                $used[basename((string) $value)] = true;
            }
        }
    }

    $directories = [
        __DIR__ . '/../uploads/profile-pictures',
        __DIR__ . '/../uploads/logos',
        __DIR__ . '/../uploads/docs',
    ];

    $deleted = 0;

    foreach ($directories as $dir) {
        if (!is_dir($dir)) {
            continue;
        }

        foreach (scandir($dir) as $name) {
            if (
                !preg_match(
                    '/^[a-f0-9]{32}\.(png|jpg|jpeg|pdf)$/',
                    $name
                )
            ) {
                continue;
            }

            if (isset($used[$name])) {
                continue;
            }

            $path = $dir . DIRECTORY_SEPARATOR . $name;

            if (
                is_file($path) &&
                (time() - filemtime($path)) > $maxAgeSeconds &&
                @unlink($path)
            ) {
                $deleted++;
            }
        }
    }

    return $deleted;
}